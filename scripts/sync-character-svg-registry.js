// Syncs authoritative unflattened assets/characters/*/master_layered.svg files into
// src/presentation/characterSvgRegistry.js so live 16-layer 2D animation works seamlessly
// over BOTH file:// (zero-CORS local launch) and HTTP / Mobile PWA.
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CHAR_DIR = path.join(ROOT, 'assets', 'characters');
const OUT_FILE = path.join(ROOT, 'src', 'presentation', 'characterSvgRegistry.js');

const entries = {};
const warnings = [];
for (const folder of fs.readdirSync(CHAR_DIR).sort()) {
  const folderPath = path.join(CHAR_DIR, folder);
  if (!fs.statSync(folderPath).isDirectory()) continue;
  const svgFile = path.join(folderPath, 'master_layered.svg');
  const manifestFile = path.join(folderPath, 'rig_manifest.json');
  if (fs.existsSync(svgFile)) {
    const svgText = fs.readFileSync(svgFile, 'utf8');
    const relKey = `assets/characters/${folder}/master_layered.svg`;
    entries[relKey] = svgText;
    if (!fs.existsSync(manifestFile)) {
      warnings.push(`[WARN] ${folder}: master_layered.svg found without rig_manifest.json`);
    }
    const hrefMatches = svgText.match(/href="(assets\/[^"]+)"/g) || [];
    for (const m of hrefMatches) {
      const relAsset = m.slice(6, -1);
      if (!fs.existsSync(path.join(ROOT, relAsset))) {
        warnings.push(`[WARN] ${folder}: missing referenced SVG image ${relAsset}`);
      }
    }
  }
}

const out = [
  '// AUTO-GENERATED by scripts/sync-character-svg-registry.js from assets/characters/*/master_layered.svg',
  '// Provides zero-CORS file:// & instant 0ms-flash 16-layer SVG access for V.CharacterRig.',
  '(function (global) {',
  "  'use strict';",
  '  const V = (global.Valency = global.Valency || {});',
  `  V.CHARACTER_SVG_SOURCES = ${JSON.stringify(entries, null, 2)};`,
  '})(typeof window !== "undefined" ? window : globalThis);',
  '',
].join('\n');

fs.writeFileSync(OUT_FILE, out, 'utf8');
console.log(`Synced ${Object.keys(entries).length} layered SVG source(s) -> ${OUT_FILE}`);
if (warnings.length > 0) {
  console.warn(warnings.join('\n'));
}
